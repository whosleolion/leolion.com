// Headless smoke test of the real page. Usage: node browser-smoke.mjs <url> <outdir>
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const url = process.argv[2] || 'http://localhost:8765/index.html';
const out = process.argv[3] || '.';
const browser = await chromium.launch();
const errors = [];
let failed = 0;
const openSec = async (page, n) => { const el = await page.$(`details.sect[data-sec="${n}"]`); if (el && !(await el.getAttribute('open') !== null)) await page.click(`details.sect[data-sec="${n}"] > summary`); };
const ok = (n, c, d) => { if (!c) { failed++; console.log('FAIL', n, d ?? ''); } else console.log('ok  ', n); };
for (const [name, vp, scheme] of [['phone-dark', { width: 390, height: 844 }, 'dark'], ['desktop-light', { width: 1100, height: 900 }, 'light']]) {
  const ctx = await browser.newContext({ viewport: vp, colorScheme: scheme, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  page.on('console', m => { if (m.type() === 'error' && !/fonts\.g|ERR_|Failed to load resource/.test(m.text())) errors.push(name + ': ' + m.text()); });
  page.on('pageerror', e => errors.push(name + ': ' + e.message));
  await page.goto(url, { waitUntil: 'load' });
  await page.waitForSelector('.res');
  ok(name + ' initial price shown', (await page.textContent('.price .big')).length > 0);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  ok(name + ' no horizontal overflow', overflow <= 0, overflow);
  await page.screenshot({ path: `${out}/${name}-1.png`, fullPage: true });
  await page.fill('#q', 'sell 5 rare potions black market rush');
  await page.waitForSelector('.res');
  ok(name + ' details start closed', await page.isHidden('#whyPanel'));
  ok(name + ' minimal: no chips visible by default', !(await page.isVisible('.chip')));
  await page.click('[data-k=why]');
  ok(name + ' chips rendered', (await page.$$('.chip')).length >= 5);
  ok(name + ' options start closed', await page.isHidden('#optsPanel'));
  await page.click('[data-k=opts]');
  ok(name + ' options panel', await page.isVisible('#optsPanel .opt'));
  const before = await page.textContent('.price .big');
  await page.click('.opt >> nth=0');
  const after = await page.textContent('.price .big');
  ok(name + ' option changes price', before !== after, [before, after]);
  ok(name + ' text box follows chips', (await page.inputValue('#q')).length > 10);
  const n0 = (await page.$$('.chip')).length;
  await page.click('.chip .x >> nth=-1');
  ok(name + ' chip remove', (await page.$$('.chip')).length === n0 - 1);
  await page.fill('#q', 'blak market longsword');
  ok(name + ' suggestion', !!(await page.$('[data-act=fix]')));
  await page.click('[data-act=fix]');
  ok(name + ' suggestion applied', (await page.inputValue('#q')).includes('black market'));
  await page.fill('#q', 'sell sword in capital and village');
  ok(name + ' conflict UI', !!(await page.$('.conflict')));
  await page.click('.conflict [data-act=resolve] >> nth=0');
  ok(name + ' conflict resolved', !(await page.$('.conflict')));
  await page.click('#tabTap');
  await page.click('.fstep[data-step=item] > summary');
  await page.click('[data-act=f-cat][data-v=travel]');
  await page.click('[data-act=f-item] >> nth=0');
  ok(name + ' flow gives result', !!(await page.$('.res')));
  await page.screenshot({ path: `${out}/${name}-flow.png`, fullPage: true });
  ok(name + ' flow steps start collapsed after picking', (await page.$$('.fstep[open]')).length <= 1);
  await page.click('#tabType');
  await page.click('#worldBtn');
  ok(name + ' drawer opens', await page.isVisible('#drawer'));
  ok(name + ' settings sections start closed', (await page.$$('details.sect[open]')).length === 0);
  await page.click('details.sect[data-sec=Dials] > summary');
  await page.click('[data-bind="dial.round"]');
  await page.click('details.sect[data-sec=Dials] > summary');
  await page.screenshot({ path: `${out}/${name}-world.png` });
  await openSec(page, 'Your worlds');
  await page.click('[data-act=w-select][data-id=modern]');
  await page.click('[data-act=close-world]');
  await page.fill('#q', '6 months of rent in a city');
  const price = await page.textContent('.price .big');
  ok(name + ' modern world prices in dollars', /^\$[\d,]+/.test(price), price);
  ok(name + ' modern world offers unspecified options', !!(await page.$('[data-k=opts]')));
  await page.screenshot({ path: `${out}/${name}-modern.png`, fullPage: true });
  await page.click('#worldBtn'); await openSec(page, 'Your worlds'); await page.click('[data-act=w-select][data-id=vcm]'); await page.click('[data-act=close-world]');
  // unknown words: guess, nudge, set
  await page.fill('#q', '10 monster parts');
  ok(name + ' unknown word shows the guess card', !!(await page.$('.guess')));
  await page.click('.cand >> nth=0');
  ok(name + ' guess shows a proposed price', /about/.test(await page.textContent('.adjust .setline')));
  const p0 = await page.textContent('.adjust .gp');
  await page.click('[data-act=g-raise]');
  ok(name + ' raise changes the proposal', p0 !== (await page.textContent('.adjust .gp')), p0);
  await page.screenshot({ path: `${out}/${name}-guess.png`, fullPage: true });
  await page.click('[data-act=g-set]');
  ok(name + ' set it prices the thing', !(await page.$('.guess')) && !!(await page.$('.res')));
  ok(name + ' set it priced ten of them', /Monster parts/i.test(await page.textContent('.res .what')));
  // hostile import must not brick the app or run script
  let alerts = 0; page.on('dialog', d => { alerts++; d.dismiss(); });
  await page.click('#worldBtn');
  await openSec(page, 'Back up and share');
  await page.fill('#importBox', '{"name":"bad","items":[{}]}');
  await page.click('[data-act=w-import]');
  await page.fill('#importBox', '{"id":"i","name":"i","currency":{"denominations":[{"id":"gp","name":"gp","bu":"\\"><img src=x onerror=alert(1)>"}]},"dials":{"priceLevel":"\\"><img src=x onerror=alert(2)>"}}');
  await page.click('[data-act=w-import]');
  await page.click('[data-act=close-world]');
  await page.fill('#q', 'longsword');
  await page.reload({ waitUntil: 'load' });
  await page.waitForSelector('.res, .empty');
  ok(name + ' hostile import: app still boots after reload', !!(await page.$('#q')));
  ok(name + ' hostile import: no script ran', alerts === 0, alerts);
  // focus stays put while editing a field in the drawer
  await page.click('#worldBtn');
  await page.click('details.sect[data-sec=Money] > summary');
  await page.focus('[data-bind=wage]');
  await page.fill('[data-bind=wage]', '30 cp');
  await page.keyboard.press('Tab');
  ok(name + ' drawer keeps focus after an edit', await page.evaluate(() => document.activeElement && document.activeElement.tagName !== 'BODY'));
  await page.click('[data-act=close-world]');
  await page.fill('#q', '');
  ok(name + ' empty state', !!(await page.$('.empty')));
  await page.fill('#q', 'price for train ride between two major capital cities, 3 days travel expensive');
  await page.screenshot({ path: `${out}/${name}-2.png`, fullPage: true });
  await ctx.close();
}
await browser.close();
if (errors.length) { console.log('CONSOLE ERRORS', errors); failed++; }
console.log(failed ? failed + ' FAILED' : 'all smoke checks passed');
process.exit(failed ? 1 : 0);
