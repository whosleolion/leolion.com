// Science fiction item list. Prices are in credits, and 1 base unit is 1 credit.
// Entry shape: { id: 'good.s-name', name, kind, src: 'scifi', bu, unit, tags: [], aliases: [], spread, basis? }
// Calibrated so 1 credit buys about what a modern US dollar does. All numbers are original to Fool's Gold.
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
// Row: "name ; price ; unit ; extra tags ; aliases ; basis"
function s(kind, tags, list, extra = {}) {
  return list.map(line => {
    const [name, price, unit, more, aliases, basis] = line.split(';').map(x => x.trim());
    const e = {
      id: kind + '.s-' + slug(name), name, kind, src: 'scifi', bu: Math.round(parseFloat(price.replace(/,/g, ''))), unit: unit || 'each',
      tags: [...tags, ...(more ? more.split(/\s+/) : [])], aliases: aliases ? aliases.split(',').map(x => x.trim()).filter(Boolean) : [],
      spread: 0.15, ...extra,
    };
    if (basis) e.basis = basis;
    return e;
  });
}
